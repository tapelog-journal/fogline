import { readFileSync, writeFileSync } from "node:fs";
const out = (n) => JSON.parse(readFileSync(new URL(`../../out/${n}.sol/${n}.json`, import.meta.url))).abi;
const src = `// generated by scripts/gen-abi.mjs from forge build output\n` +
  `export const foglineAbi = ${JSON.stringify(out("Fogline"))} as const;\n` +
  `export const mockUsdcAbi = ${JSON.stringify(out("MockUSDC"))} as const;\n` +
  `export const cosmeticsAbi = ${JSON.stringify(out("FoglineCosmetics"))} as const;\n`;
writeFileSync(new URL("../src/abi.ts", import.meta.url), src);
console.log("wrote src/abi.ts");
